/// The computer the new-game dialog offers first: Medium, with the person
/// moving first.
const ComputerOpponent _firstOffer = ComputerOpponent(
  difficulty: Difficulty.medium,
  player: Player.white,
);

/// What the new-game dialog shows chosen: whether to play the computer,
/// and the [computer] to play if so, which holds both its difficulty and the
/// colour it plays.
///
/// While a friend is chosen, the dialog hides the computer's choices, but
/// [computer] keeps them: choosing the computer again shows them as they
/// were.
///
/// Plain data generated by freezed: value equality, `copyWith` and
/// `toString`, with no behaviour (docs/adr/0011).
@freezed
abstract class NewGameChoices with _$NewGameChoices {
  const factory NewGameChoices({
    @Default(false) bool againstComputer,
    @Default(_firstOffer) ComputerOpponent computer,
  }) = _NewGameChoices;
}

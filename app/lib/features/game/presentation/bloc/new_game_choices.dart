part 'new_game_choices.freezed.dart';

/// The computer the new-game screen offers first: Medium, with the person
/// moving first.
const ComputerOpponent _firstOffer = ComputerOpponent(
  difficulty: Difficulty.medium,
  player: Player.white,
);

/// What the new-game screen shows chosen: whether to play the computer, and
/// which [computer]. The computer's settings stay while a friend is chosen,
/// so choosing the computer again brings them back.
///
/// Plain data generated by freezed: value equality, `copyWith` and
/// `toString`, with no behaviour (docs/adr/0011).
@freezed
abstract class NewGameChoices with _$NewGameChoices {
  const factory NewGameChoices({
    @Default(false) bool againstComputer,
    @Default(_firstOffer) ComputerOpponent computer,
  }) = _NewGameChoices;
}

import 'package:cephalopod/features/game/presentation/models/captured_die_ui.dart';
import 'package:cephalopod/features/game/presentation/models/computer_move_ui.dart';
import 'package:freezed_annotation/freezed_annotation.dart';

part 'played_move_ui.freezed.dart';

/// A move that was just played, by either side, as the screen shows it.
///
/// The screen has one only when a move led to it, not when a turn was taken
/// back or played again, or another game opened: the board animates its
/// dice only then. [computer] says what the computer played, when it was the
/// computer's move, so a screen reader can say it.
///
/// [captured] are the dice the move took off the board, for the effects
/// that show a capture. [celebrate] says the move won the game for the
/// player: against the computer, the person beat it; between two people,
/// the game ended, which always has a winner on this device.
///
/// A UI model (docs/adr/0015): plain data generated by freezed
/// (docs/adr/0011).
@freezed
abstract class PlayedMoveUi with _$PlayedMoveUi {
  const factory PlayedMoveUi({
    ComputerMoveUi? computer,
    @Default(<CapturedDieUi>[]) List<CapturedDieUi> captured,
    @Default(false) bool celebrate,
  }) = _PlayedMoveUi;
}

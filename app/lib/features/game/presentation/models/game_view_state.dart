part 'game_view_state.freezed.dart';

/// Everything the game screen shows: the [board], the [headline] above it,
/// how many dice each side has on the board ([tally]), the [capture]
/// controls while a capture is being chosen, whether the board takes taps
/// ([canTap]), whether a turn can be taken back ([canUndo]) or played
/// again ([canRedo]), and whether a hint can be asked for ([canHint]).
///
/// [hint] is the hint on the board, if there is one, as a screen reader
/// says it; the board marks it too.
///
/// [playedMove] is the move just played, by either side, that led to this
/// screen. It stays until the game changes in another way: a turn taken back
/// or played again, a new game, or a saved one opened. The board animates its
/// dice only after a move, and a screen reader says the computer's move
/// before the headline.
///
/// A UI model (docs/adr/0015): plain data generated by freezed
/// (docs/adr/0011).
@freezed
abstract class GameViewState with _$GameViewState {
  const factory GameViewState({
    required BoardUi board,
    required HeadlineUi headline,
    required DiceTallyUi tally,
    CaptureUi? capture,
    PlayedMoveUi? playedMove,
    HintUi? hint,
    @Default(true) bool canTap,
    @Default(false) bool canUndo,
    @Default(false) bool canRedo,
    @Default(false) bool canHint,
  }) = _GameViewState;
}
